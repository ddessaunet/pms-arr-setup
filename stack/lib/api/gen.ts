// stack/lib/api/gen.ts — the API types of the apps that publish an OpenAPI spec,
// generated from that spec at the version running on the box.
//
//   bun stack/lib/api/gen.ts            regenerate every file (task types:gen)
//   bun stack/lib/api/gen.ts --check    compare each file's version with the
//                                       running app; changes nothing (task types:check)
//
// Each app's /system/status gives its version; the spec comes from the app's
// own repo at that tag, and openapi-typescript (a dev dependency) turns it into
// stack/lib/api/<app>.d.ts, whose header records the version. The scripts use
// these with `import type` only, so nothing here exists at runtime and the
// install leaves stack/lib/api/ out.
//
// The weekly updater moves the apps on, so a version behind is normal and only
// a reason to regenerate when a port needs a new field.
//
// Exit: 0 written, or every file matches · 1 a file is behind or missing ·
// 2 usage · 3 an app or its spec could not be read.

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { headerHelp, parseCli } from '../cli.ts';
import { envGet, type Env } from '../env.ts';
import { runMain } from '../exit.ts';
import { httpCode, jsonOf, makeHttp, type Http } from '../http.ts';
import { out, type Log } from '../log.ts';
import { run, type Run } from '../run.ts';

export interface ApiApp {
  name: string;
  /** Its URL from this box, and the variable that overrides it. */
  url: string;
  urlEnv: string;
  keyEnv: string;
  api: 'v1' | 'v3';
  /** The OpenAPI spec at a version's tag. */
  spec: (version: string) => string;
}

export const APPS: readonly ApiApp[] = [
  {
    name: 'prowlarr',
    url: 'http://127.0.0.1:9696',
    urlEnv: 'PROWLARR_URL',
    keyEnv: 'PROWLARR_API_KEY',
    api: 'v1',
    spec: (v) => `https://raw.githubusercontent.com/Prowlarr/Prowlarr/v${v}/src/Prowlarr.Api.V1/openapi.json`,
  },
];

const VERSION_LINE = /^\/\/ version: (\S+)$/m;

/** The version a generated file was made from; undefined when it has none. */
export function versionOf(text: string): string | undefined {
  return VERSION_LINE.exec(text)?.[1];
}

/** The header that goes above openapi-typescript's output. */
export function header(app: ApiApp, version: string): string {
  return [
    `// stack/lib/api/${app.name}.d.ts — ${app.name}'s API types, generated by \`task types:gen\``,
    `// from ${app.spec(version)}.`,
    "// Don't edit: regenerate. Import with `import type` only.",
    `// version: ${version}`,
    '',
  ].join('\n');
}

export interface Deps {
  http: Http;
  run: Run;
  log: Log;
  env: Env;
  repo: string;
}

async function runningVersion(app: ApiApp, deps: Deps): Promise<string | undefined> {
  const url = deps.env[app.urlEnv] || app.url;
  const key = envGet(app.keyEnv, { repo: deps.repo, env: deps.env });
  const r = await deps.http(`${url}/api/${app.api}/system/status`, {
    headers: { 'X-Api-Key': key },
    timeoutMs: 15_000,
  });
  const version = (jsonOf(r) as { version?: unknown } | undefined)?.version;
  if (r.status !== 200 || typeof version !== 'string') {
    deps.log(`  FAIL  ${app.name}: version from ${url} (HTTP ${httpCode(r.status)})`);
    return undefined;
  }
  return version;
}

export async function main(argv: readonly string[], deps: Deps): Promise<number> {
  const { log } = deps;
  const cli = parseCli(argv, { flags: ['--check'], usage: 'usage: gen.ts [--check]' });
  if (cli.help) {
    log(headerHelp(await Bun.file(import.meta.path).text()));
    return 0;
  }
  const dir = join(deps.repo, 'stack/lib/api');
  let rc = 0;
  for (const app of APPS) {
    const file = join(dir, `${app.name}.d.ts`);
    let have: string | undefined;
    try {
      have = versionOf(readFileSync(file, 'utf8'));
    } catch {
      have = undefined;
    }
    const running = await runningVersion(app, deps);
    if (running === undefined) return 3;

    if (cli.flags['--check']) {
      if (have === running) log(`  ok       ${app.name} ${running}`);
      else {
        log(`  BEHIND   ${app.name}: types are ${have ?? 'missing'}, running ${running} — task types:gen`);
        rc = 1;
      }
      continue;
    }

    const spec = await deps.http(app.spec(running), { timeoutMs: 60_000, redirect: 'follow' });
    if (spec.status !== 200 || jsonOf(spec) === undefined) {
      log(`  FAIL  ${app.name}: spec ${app.spec(running)} (HTTP ${httpCode(spec.status)})`);
      return 3;
    }
    const tmp = mkdtempSync(join(tmpdir(), 'api-gen-'));
    try {
      writeFileSync(join(tmp, 'spec.json'), spec.text);
      const gen = await deps.run(
        [
          process.execPath,
          '--bun',
          join(deps.repo, 'node_modules/.bin/openapi-typescript'),
          join(tmp, 'spec.json'),
          '-o',
          join(tmp, 'out.d.ts'),
        ],
        { timeoutMs: 120_000 },
      );
      if (gen.code !== 0) {
        log(`  FAIL  ${app.name}: openapi-typescript (rc ${gen.code}): ${gen.stderr.trim().slice(0, 300)}`);
        return 3;
      }
      writeFileSync(file, header(app, running) + readFileSync(join(tmp, 'out.d.ts'), 'utf8'));
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
    log(`  wrote    stack/lib/api/${app.name}.d.ts (${have ?? 'new'} → ${running})`);
  }
  return rc;
}

if (import.meta.main) {
  await runMain(() =>
    main(Bun.argv.slice(2), {
      http: makeHttp(),
      run,
      log: out,
      env: process.env,
      repo: resolve(import.meta.dir, '../../..'),
    }),
  );
}
